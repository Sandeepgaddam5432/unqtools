#!/usr/bin/env node
/**
 * UnQTools — Generate docs/TOOLS-INDEX.md
 *
 * Walks every src/tools/<category>/<tool-id>/manifest.ts, transpiles + evaluates
 * it, and writes a single human-readable markdown catalog of ALL tools.
 *
 * Usage: `node scripts/generate-tools-index.mjs`
 * Output: docs/TOOLS-INDEX.md
 *
 * READ-ONLY over src/. Only docs/TOOLS-INDEX.md is written.
 */
import fs from "node:fs";
import path from "node:path";
import Module from "node:module";
import ts from "typescript";

const ROOT = process.cwd();
const TOOLS_DIR = path.join(ROOT, "src/tools");
const OUT = path.join(ROOT, "docs/TOOLS-INDEX.md");

const CATEGORY_LABELS = {
  pdf: "PDF & Document",
  image: "Image & Graphics",
  "audio-video": "Audio & Video",
  developer: "Developer & Code",
  seo: "SEO & Marketing",
  calculators: "Calculators & Converters",
  text: "Text & Writing",
  "network-security": "Network, Security & Privacy",
  file: "File Management, Archiving & Compression",
  business: "Business & Productivity",
  education: "Education & Learning",
  social: "Social Media",
  ai: "AI & Smart Tools",
};

const CATEGORY_ORDER = [
  "pdf",
  "image",
  "audio-video",
  "developer",
  "seo",
  "calculators",
  "text",
  "network-security",
  "file",
  "business",
  "education",
  "social",
  "ai",
];

function findManifests(dir, acc = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) findManifests(full, acc);
    else if (entry.name === "manifest.ts") acc.push(full);
  }
  return acc;
}

function loadManifest(file) {
  const src = fs.readFileSync(file, "utf8");
  const js = ts.transpileModule(src, {
    compilerOptions: {
      module: ts.ModuleKind.CommonJS,
      target: ts.ScriptTarget.ES2020,
      esModuleInterop: true,
    },
    fileName: file,
  }).outputText;
  const m = new Module(file);
  m.filename = file;
  m.paths = Module._nodeModulePaths(path.dirname(file));
  m._compile(js, file);
  return m.exports.manifest;
}

function escapeMd(text) {
  return String(text ?? "")
    .replace(/\|/g, "\\|")
    .replace(/\r?\n/g, " ")
    .trim();
}

const files = findManifests(TOOLS_DIR);
const tools = [];

for (const file of files) {
  try {
    const man = loadManifest(file);
    if (!man || !man.id) continue;
    tools.push({
      id: man.id,
      name: man.name,
      description: man.description,
      category: man.category,
      keywords: Array.isArray(man.keywords) ? man.keywords : [],
      icon: man.icon ?? "",
      requiresNetwork: Boolean(man.requiresNetwork),
      status: man.status ?? "planned",
    });
  } catch (e) {
    console.error("SKIP", path.relative(ROOT, file), "-", e.message);
  }
}

// Sanity: every category in the manifest must be known.
const unknown = [...new Set(tools.map((t) => t.category))].filter(
  (c) => !CATEGORY_LABELS[c]
);
if (unknown.length) {
  console.error("Unknown categories:", unknown.join(", "));
  process.exit(1);
}

tools.sort((a, b) => a.id.localeCompare(b.id));

const byCat = new Map();
for (const t of tools) {
  if (!byCat.has(t.category)) byCat.set(t.category, []);
  byCat.get(t.category).push(t);
}

const statusCount = tools.reduce((acc, t) => {
  acc[t.status] = (acc[t.status] ?? 0) + 1;
  return acc;
}, {});
const offlineCount = tools.filter((t) => !t.requiresNetwork).length;

const L = [];
L.push("# UnQTools — Complete Tool Catalog (All 1,704 Tools)");
L.push("");
L.push("> Auto-generated by `node scripts/generate-tools-index.mjs`. Do not edit by hand.");
L.push("> Source of truth: the `manifest.ts` files under `src/tools/<category>/<id>/`.");
L.push("");
L.push(`- **Total tools:** ${tools.length}`);
L.push(`- **Categories:** ${CATEGORY_ORDER.length}`);
L.push(`- **Offline-capable (no network needed):** ${offlineCount} (${Math.round((offlineCount / tools.length) * 100)}%)`);
L.push(`- **Status breakdown:** ${Object.entries(statusCount)
  .map(([k, v]) => `**${k}:** ${v}`)
  .join(" · ")}`);
L.push("");
L.push("Every tool has its own page at `/tools/<id>` and is searchable from the command palette.");
L.push("");
L.push("## Contents");
L.push("");
for (const cat of CATEGORY_ORDER) {
  const list = byCat.get(cat) ?? [];
  L.push(`- [${CATEGORY_LABELS[cat]} (${list.length})](#${cat.replace(/[^a-z0-9]+/g, "-")})`);
}
L.push("");
L.push("---");
L.push("");

let rank = 0;
for (const cat of CATEGORY_ORDER) {
  const list = byCat.get(cat) ?? [];
  L.push(`## ${CATEGORY_LABELS[cat]}`);
  L.push("");
  L.push(`**${list.length} tools** — route prefix: \`/tools/<id>\``);
  L.push("");
  L.push("| # | Tool | ID / URL | Status | Offline | Description |");
  L.push("|---|------|----------|--------|---------|-------------|");
  for (const t of list) {
    rank += 1;
    const status = t.status === "done" ? "✅ done" : t.status === "beta" ? "🧪 beta" : "⏳ planned";
    const offline = t.requiresNetwork ? "❌ needs net" : "✅ offline";
    L.push(
      `| ${rank} | **${escapeMd(t.name)}** | [\`${t.id}\`](/tools/${t.id}) | ${status} | ${offline} | ${escapeMd(t.description)} |`
    );
  }
  L.push("");
  L.push("---");
  L.push("");
}

L.push(`_${tools.length} tools · generated on ${new Date().toISOString().slice(0, 10)}._`);

fs.writeFileSync(OUT, L.join("\n"), "utf8");
console.log(`Wrote ${OUT}: ${tools.length} tools across ${CATEGORY_ORDER.length} categories.`);
