/**
 * PDF to AZW3 Converter — pure-JS simplified KF8 (Kindle Format 8) generator.
 *
 * AZW3 structure (simplified):
 *   1. PalmDB header (78 bytes) — type 'BOOK', creator 'MOBI'
 *   2. Record info table — recordCount × 8 bytes
 *   3. Padding (2 bytes)
 *   4. Records:
 *        - Record 0: PalmDOC header + MOBI header + EXTH + KF8 boundary marker
 *        - Record 1: Cover page HTML (simple <h1>title</h1><p>author</p>)
 *        - Records 2..N: HTML text records (max 4096 bytes each)
 *        - Last record: KF8 boundary 'BOUNDARY' marker
 *
 * Real AZW3 files have a much more complex structure (KF8 index, flow items,
 * vocab indexes, etc.). We produce a minimal readable subset.
 */

