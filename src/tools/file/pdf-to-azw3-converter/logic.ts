// ===== History =====

const HISTORY_KEY = "unqtools-pdf-to-azw3-history";
const MAX_HISTORY = 10;

export interface HistoryEntry {
  fileName: string;
  pdfBytes: number;
  azw3Bytes: number;
  recordCount: number;
  wordCount: number;
  convertedAt: string;
}

export function loadHistory(): HistoryEntry[] {
  if (typeof localStorage === "undefined") return [];
  try {
    const raw = localStorage.getItem(HISTORY_KEY);
    if (!raw) return [];
    const parsed = JSON.parse(raw);
    return Array.isArray(parsed) ? parsed.slice(0, MAX_HISTORY) : [];
  } catch { return []; }
}

export function saveToHistory(entry: HistoryEntry): HistoryEntry[] {
  if (typeof localStorage === "undefined") return [];
  const updated = [entry, ...loadHistory()].slice(0, MAX_HISTORY);
  try { localStorage.setItem(HISTORY_KEY, JSON.stringify(updated)); } catch { /* ignore */ }
  return updated;
}

export function clearHistory(): void {
  if (typeof localStorage === "undefined") return;
  try { localStorage.removeItem(HISTORY_KEY); } catch { /* ignore */ }
}

// ===== Shareable URL =====

export function buildShareUrl(opts: Azw3Options): string {
  if (typeof window === "undefined") return "";
  const params = new URLSearchParams();
  if (opts.pageRange) params.set("pages", opts.pageRange);
  params.set("mode", opts.chapterMode);
  params.set("enc", opts.encoding);
  if (opts.title && opts.title !== DEFAULT_OPTIONS.title) params.set("title", opts.title);
  if (opts.author && opts.author !== DEFAULT_OPTIONS.author) params.set("author", opts.author);
  params.set("lang", opts.language);
  return `${window.location.origin}${window.location.pathname}#${params.toString()}`;
}

export function parseShareUrl(hash: string): Partial<Azw3Options> | null {
  if (!hash || !hash.startsWith("#")) return null;
  const params = new URLSearchParams(hash.slice(1));
  if (!params.has("mode") && !params.has("pages")) return null;
  const mode = (params.get("mode") ?? "page") as Azw3ChapterMode;
  const validModes: Azw3ChapterMode[] = ["page", "heading", "single"];
  const enc = (params.get("enc") ?? "utf-8") as Azw3Encoding;
  const validEncs: Azw3Encoding[] = ["utf-8", "cp1252"];
  return {
    pageRange: params.get("pages") ?? "",
    chapterMode: validModes.includes(mode) ? mode : "page",
    encoding: validEncs.includes(enc) ? enc : "utf-8",
    title: params.get("title") ?? "",
    author: params.get("author") ?? "",
    language: params.get("lang") ?? "en",
  };
}
