/**
 * PDF to PowerPoint Converter — pure-JS PPTX (OOXML Presentation) generator.
 *
 * Pipeline:
 *   1. Extract text from PDF using pdf-to-text-converter's extractor.
 *   2. Build slides: one slide per PDF page (title = first line, bullets = rest).
 *   3. Generate the OOXML ZIP structure:
 *        - [Content_Types].xml
 *        - _rels/.rels
 *        - ppt/presentation.xml
 *        - ppt/_rels/presentation.xml.rels
 *        - ppt/presProps.xml
 *        - ppt/viewProps.xml
 *        - ppt/theme/theme1.xml
 *        - ppt/slideMasters/slideMaster1.xml
 *        - ppt/slideMasters/_rels/slideMaster1.xml.rels
 *        - ppt/slideLayouts/slideLayout1.xml
 *        - ppt/slideLayouts/_rels/slideLayout1.xml.rels
 *        - ppt/slides/slide1.xml, slide2.xml, ...
 *        - ppt/slides/_rels/slideN.xml.rels
 *   4. Package everything into a ZIP (reuse createZipBlob).
 */

