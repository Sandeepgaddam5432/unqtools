// ===== Top-level conversion =====

export async function convertPdfToPptx(
  pdfBytes: Uint8Array,
  opts: PptxOptions = DEFAULT_OPTIONS,
  outputFileName: string = "converted.pptx",
): Promise<ToolResult<PptxResult>> {
  const textOptions: TextOptions = {
    pageRange: opts.pageRange,
    lineSeparator: "\n",
    pageSeparator: "",
    trimLines: true,
    removeEmptyLines: false,
    lineNumbers: false,
    addBom: false,
  };
  const textResult = await extractPdfText(pdfBytes, textOptions);
  if (!textResult.ok) {
    return { ok: false, error: textResult.error };
  }
  const pageTexts = textResult.output.pages.map((p) => p.text);
  const slides = buildSlides(pageTexts, opts);
  if (slides.length === 0) {
    return { ok: false, error: "No text content found in the PDF." };
  }
  const enc = new TextEncoder();
  const files: ZipFile[] = [];
  files.push({ name: "[Content_Types].xml", data: enc.encode(generateContentTypesXml(slides.length)) });
  files.push({ name: "_rels/.rels", data: enc.encode(generateRootRelsXml()) });
  files.push({ name: "ppt/presentation.xml", data: enc.encode(generatePresentationXml(slides.length, opts)) });
  files.push({ name: "ppt/_rels/presentation.xml.rels", data: enc.encode(generatePresentationRelsXml(slides.length)) });
  files.push({ name: "ppt/presProps.xml", data: enc.encode(generatePresPropsXml()) });
  files.push({ name: "ppt/viewProps.xml", data: enc.encode(generateViewPropsXml()) });
  files.push({ name: "ppt/theme/theme1.xml", data: enc.encode(generateThemeXml(opts)) });
  files.push({ name: "ppt/slideMasters/slideMaster1.xml", data: enc.encode(generateSlideMasterXml()) });
  files.push({ name: "ppt/slideMasters/_rels/slideMaster1.xml.rels", data: enc.encode(generateSlideMasterRelsXml()) });
  files.push({ name: "ppt/slideLayouts/slideLayout1.xml", data: enc.encode(generateSlideLayoutXml()) });
  files.push({ name: "ppt/slideLayouts/_rels/slideLayout1.xml.rels", data: enc.encode(generateSlideLayoutRelsXml()) });
  for (const slide of slides) {
    const isTitleSlide = opts.insertTitleSlide && slide.number === 1;
    files.push({ name: `ppt/slides/slide${slide.number}.xml`, data: enc.encode(generateSlideXml(slide, opts, isTitleSlide)) });
    files.push({ name: `ppt/slides/_rels/slide${slide.number}.xml.rels`, data: enc.encode(generateSlideRelsXml()) });
  }
  const blob = createZipBlob(files);
  const wordCount = slides.reduce((s, sl) => s + sl.wordCount, 0);
  const charCount = slides.reduce((s, sl) => s + sl.title.length + sl.bullets.join(" ").length, 0);
  return {
    ok: true,
    output: {
      blob,
      fileName: outputFileName,
      slideCount: slides.length,
      wordCount,
      charCount,
      pageCount: textResult.output.pageCount,
      pptxBytes: blob.size,
      slides,
    },
  };
}

