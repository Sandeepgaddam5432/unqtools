// ===== Types =====

export type SlideLayout = "title-content" | "content-only";

export interface PptxOptions {
  /** Page range (e.g. "1-3,5"). Empty = all pages. */
  pageRange: string;
  /** Slide layout. */
  layout: SlideLayout;
  /** Custom title slide title. */
  titleSlideTitle: string;
  /** Custom title slide subtitle. */
  titleSlideSubtitle: string;
  /** Insert a title slide as slide 1 (uses the values above). */
  insertTitleSlide: boolean;
  /** Base font size in points for body text. */
  fontSize: number;
  /** Slide aspect ratio. */
  aspectRatio: "16:9" | "4:3";
  /** Accent color for titles (hex without #). */
  accentColor: string;
}

export const DEFAULT_OPTIONS: PptxOptions = {
  pageRange: "",
  layout: "title-content",
  titleSlideTitle: "Converted from PDF",
  titleSlideSubtitle: "Generated by UnQTools",
  insertTitleSlide: true,
  fontSize: 18,
  aspectRatio: "16:9",
  accentColor: "1F4E79",
};

export interface SlideContent {
  /** 1-indexed slide number. */
  number: number;
  /** Slide title (empty for content-only). */
  title: string;
  /** Bullet point paragraphs. */
  bullets: string[];
  /** Word count. */
  wordCount: number;
}

export interface PptxResult {
  blob: Blob;
  fileName: string;
  slideCount: number;
  wordCount: number;
  charCount: number;
  pageCount: number;
  pptxBytes: number;
  slides: SlideContent[];
}

// ===== Slide dimensions =====

/** Get slide dimensions in EMUs (English Metric Units: 914400 per inch). */
export function getSlideDimensions(ratio: "16:9" | "4:3"): { width: number; height: number } {
  // PowerPoint standard: 16:9 = 13.333 x 7.5 inches; 4:3 = 10 x 7.5 inches
  if (ratio === "16:9") {
    return { width: 12192000, height: 6858000 }; // 13.333" x 7.5"
  }
  return { width: 9144000, height: 6858000 }; // 10" x 7.5"
}

// ===== Slide building =====

/**
 * Build slide content from PDF page texts.
 * Each page becomes one slide: first non-empty line is the title,
 * remaining lines are bullets. Empty lines become paragraph breaks.
 */
export function buildSlides(pageTexts: string[], opts: PptxOptions): SlideContent[] {
  const slides: SlideContent[] = [];
  let number = 1;
  if (opts.insertTitleSlide) {
    slides.push({
      number: number++,
      title: opts.titleSlideTitle,
      bullets: [opts.titleSlideSubtitle].filter((s) => s !== ""),
      wordCount: countWords(opts.titleSlideTitle + " " + opts.titleSlideSubtitle),
    });
  }
  for (const pageText of pageTexts) {
    const lines = pageText.split("\n").map((l) => l.trim()).filter((l) => l !== "");
    if (lines.length === 0) continue;
    const title = opts.layout === "title-content" ? lines[0]! : "";
    const bullets = opts.layout === "title-content" ? lines.slice(1) : lines;
    slides.push({
      number: number++,
      title,
      bullets,
      wordCount: countWords(lines.join(" ")),
    });
  }
  return slides;
}

export function countWords(text: string): number {
  return text.split(/\s+/).filter((s) => s.length > 0).length;
}

// ===== Slide XML generation =====

const SLIDE_NS = "http://schemas.openxmlformats.org/presentationml/2006/main";
const REL_NS = "http://schemas.openxmlformats.org/officeDocument/2006/relationships";

/** Generate a slide XML for a title + content layout. */
export function generateSlideXml(slide: SlideContent, opts: PptxOptions, isTitleSlide: boolean = false): string {
  const dims = getSlideDimensions(opts.aspectRatio);
  const fs = Math.max(10, Math.min(60, opts.fontSize));
  const titleFs = Math.max(20, fs + 12);
  const accent = opts.accentColor.replace(/^#/, "").toUpperCase();
  const titleColor = `FF${accent}`;
  // Title text box — top of slide
  const titleBox = isTitleSlide
    ? generateTitleSlideTitle(slide.title, dims, titleFs, titleColor)
    : opts.layout === "title-content"
      ? generateTitleBox(slide.title, dims, titleFs, titleColor)
      : "";
  // Content / bullets
  let contentBox: string;
  if (isTitleSlide) {
    contentBox = generateTitleSlideSubtitle(slide.bullets[0] ?? "", dims, fs);
  } else {
    const top = opts.layout === "title-content" ? 1828800 : 457200;
    const height = opts.layout === "title-content" ? 4572000 : 5486400;
    contentBox = generateContentBox(slide.bullets, dims, top, height, fs);
  }
  return `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<p:sld xmlns:a="http://schemas.openxmlformats.org/drawingml/2006/main" xmlns:r="${REL_NS}" xmlns:p="${SLIDE_NS}">
  <p:cSld>
    <p:spTree>
      <p:nvGrpSpPr><p:cNvPr id="1" name=""/><p:cNvGrpSpPr/><p:nvPr/></p:nvGrpSpPr>
      <p:grpSpPr><a:xfrm><a:off x="0" y="0"/><a:ext cx="${dims.width}" cy="${dims.height}"/><a:chOff x="0" y="0"/><a:chExt cx="${dims.width}" cy="${dims.height}"/></a:xfrm></p:grpSpPr>
${titleBox}
${contentBox}
    </p:spTree>
  </p:cSld>
  <p:clrMapOvr><a:masterClrMapping/></p:clrMapOvr>
</p:sld>`;
}

/** Generate the title text box for a content slide. */
function generateTitleBox(title: string, dims: { width: number; height: number }, fontSize: number, color: string): string {
  const x = 457200; // 0.5 inch
  const y = 274320; // 0.3 inch
  const w = dims.width - 914400;
  const h = 1143000; // 1.25 inch
  const escaped = xmlEscape(title);
  return `      <p:sp>
        <p:nvSpPr><p:cNvPr id="2" name="Title"/><p:cNvSpPr><a:spLocks noGrp="1"/></p:cNvSpPr><p:nvPr><p:ph type="title"/></p:nvPr></p:nvSpPr>
        <p:spPr><a:xfrm><a:off x="${x}" y="${y}"/><a:ext cx="${w}" cy="${h}"/></a:xfrm><a:prstGeom prst="rect"><a:avLst/></a:prstGeom></p:spPr>
        <p:txBody><a:bodyPr wrap="square" anchor="t"/><a:lstStyle/>
          <a:p><a:r><a:rPr lang="en-US" sz="${fontSize * 100}" b="1"><a:solidFill><a:srgbClr val="${color}"/></a:solidFill></a:rPr><a:t>${escaped}</a:t></a:r></a:p>
        </p:txBody>
      </p:sp>`;
}

/** Generate the content/bullet text box. */
function generateContentBox(bullets: string[], dims: { width: number; height: number }, top: number, height: number, fontSize: number): string {
  const x = 457200;
  const w = dims.width - 914400;
  const escaped = bullets.length > 0 ? bullets.map((b) => {
    return `          <a:p><a:pPr marL="171450" indent="-171450"><a:buFont typeface="Arial"/><a:buChar char="•"/></a:pPr><a:r><a:rPr lang="en-US" sz="${fontSize * 100}"/><a:t>${xmlEscape(b)}</a:t></a:r></a:p>`;
  }).join("\n") : `          <a:p/>`;
  return `      <p:sp>
        <p:nvSpPr><p:cNvPr id="3" name="Content"/><p:cNvSpPr><a:spLocks noGrp="1"/></p:cNvSpPr><p:nvPr><p:ph type="body" idx="1"/></p:nvPr></p:nvSpPr>
        <p:spPr><a:xfrm><a:off x="${x}" y="${top}"/><a:ext cx="${w}" cy="${height}"/></a:xfrm><a:prstGeom prst="rect"><a:avLst/></a:prstGeom></p:spPr>
        <p:txBody><a:bodyPr wrap="square" anchor="t"/>
          <a:lstStyle/>
${escaped}
        </p:txBody>
      </p:sp>`;
}

