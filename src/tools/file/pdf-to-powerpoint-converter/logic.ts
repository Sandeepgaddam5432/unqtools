// ===== History =====

const HISTORY_KEY = "unqtools-pdf-to-pptx-history";
const MAX_HISTORY = 10;

export interface HistoryEntry {
  fileName: string;
  pdfBytes: number;
  pptxBytes: number;
  slideCount: number;
  wordCount: number;
  convertedAt: string;
}

export function loadHistory(): HistoryEntry[] {
  if (typeof localStorage === "undefined") return [];
  try {
    const raw = localStorage.getItem(HISTORY_KEY);
    if (!raw) return [];
    const parsed = JSON.parse(raw);
    return Array.isArray(parsed) ? parsed.slice(0, MAX_HISTORY) : [];
  } catch { return []; }
}

export function saveToHistory(entry: HistoryEntry): HistoryEntry[] {
  if (typeof localStorage === "undefined") return [];
  const updated = [entry, ...loadHistory()].slice(0, MAX_HISTORY);
  try { localStorage.setItem(HISTORY_KEY, JSON.stringify(updated)); } catch { /* ignore */ }
  return updated;
}

export function clearHistory(): void {
  if (typeof localStorage === "undefined") return;
  try { localStorage.removeItem(HISTORY_KEY); } catch { /* ignore */ }
}

// ===== Shareable URL =====

export function buildShareUrl(opts: PptxOptions): string {
  if (typeof window === "undefined") return "";
  const params = new URLSearchParams();
  if (opts.pageRange) params.set("pages", opts.pageRange);
  params.set("layout", opts.layout);
  params.set("title", opts.insertTitleSlide ? "1" : "0");
  params.set("fs", String(opts.fontSize));
  params.set("ratio", opts.aspectRatio);
  params.set("accent", opts.accentColor);
  return `${window.location.origin}${window.location.pathname}#${params.toString()}`;
}

export function parseShareUrl(hash: string): Partial<PptxOptions> | null {
  if (!hash || !hash.startsWith("#")) return null;
  const params = new URLSearchParams(hash.slice(1));
  if (!params.has("layout") && !params.has("pages")) return null;
  const layout = (params.get("layout") ?? "title-content") as SlideLayout;
  const validLayouts: SlideLayout[] = ["title-content", "content-only"];
  const fs = parseInt(params.get("fs") ?? "18", 10);
  const ratio = (params.get("ratio") ?? "16:9") as PptxOptions["aspectRatio"];
  const validRatios: PptxOptions["aspectRatio"][] = ["16:9", "4:3"];
  return {
    pageRange: params.get("pages") ?? "",
    layout: validLayouts.includes(layout) ? layout : "title-content",
    insertTitleSlide: params.get("title") !== "0",
    fontSize: isNaN(fs) ? 18 : Math.max(10, Math.min(60, fs)),
    aspectRatio: validRatios.includes(ratio) ? ratio : "16:9",
    accentColor: params.get("accent") ?? DEFAULT_OPTIONS.accentColor,
  };
}
