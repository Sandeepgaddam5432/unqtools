export function generatePresentationXml(slideCount: number, opts: PptxOptions): string {
  const dims = getSlideDimensions(opts.aspectRatio);
  const sldIds = Array.from({ length: slideCount }, (_, i) => {
    return `    <p:sldId id="${256 + i}" r:id="rId${i + 2}"/>`;
  }).join("\n");
  return `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<p:presentation xmlns:a="http://schemas.openxmlformats.org/drawingml/2006/main" xmlns:r="${REL_NS}" xmlns:p="${SLIDE_NS}" saveSubsetFonts="1">
  <p:sldMasterIdLst><p:sldMasterId id="2147483648" r:id="rId1"/></p:sldMasterIdLst>
  <p:sldIdLst>
${sldIds}
  </p:sldIdLst>
  <p:sldSz cx="${dims.width}" cy="${dims.height}" type="screen${opts.aspectRatio.replace(":", "x")}"/>
  <p:notesSz cx="6858000" cy="9144000"/>
  <p:defaultTextStyle/>
</p:presentation>`;
}

